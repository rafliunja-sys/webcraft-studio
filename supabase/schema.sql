-- WebCraft Studio: tabel permintaan konsultasi publik.
-- Jalankan sekali melalui Supabase Dashboard > SQL Editor.

create table if not exists public.consultations (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 100),
  whatsapp text not null check (char_length(trim(whatsapp)) between 8 and 25),
  service text not null check (char_length(trim(service)) between 2 and 100),
  budget text check (budget is null or char_length(budget) <= 100),
  message text not null check (char_length(trim(message)) between 10 and 2000),
  created_at timestamptz not null default now()
);

alter table public.consultations enable row level security;

-- Pengunjung hanya boleh mengirim permintaan baru. Tidak boleh membaca,
-- mengubah, atau menghapus data konsultasi.
revoke all on table public.consultations from anon, authenticated;
grant insert on table public.consultations to anon;

drop policy if exists "Anyone can submit consultation" on public.consultations;
create policy "Anyone can submit consultation"
on public.consultations
for insert
to anon
with check (
  char_length(trim(name)) between 2 and 100
  and char_length(trim(whatsapp)) between 8 and 25
  and char_length(trim(service)) between 2 and 100
  and char_length(trim(message)) between 10 and 2000
);
